# Python 的字符串是不可变的（immutable）。
# 每次字符串拼接 res += ch，Python 不能原地修改 res（因为字符串不可变），所以它必须：
# 申请一块新内存：大小 = 旧字符串长度 + 1
# 拷贝旧字符串的全部内容到新内存
# 追加新字符
# 销毁旧字符串
# 第 k 次拼接要拷贝 k 个字符，总共拷贝 (1 + 2 + 3 + \cdots + n = O(n^2)) 个字符。

# 列表 append + join 为什么快
# list.append() 是原地操作，均摊 O(1)（底层是动态数组，偶尔扩容但拷贝量远小于字符串）
# ''.join(res) 在最后一次性分配恰好大小的内存，一趟拷贝完成
# 总操作量：(O(n)) 次 append + 1 次 O(n) 的 join = O(n)。


