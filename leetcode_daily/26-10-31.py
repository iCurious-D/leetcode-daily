""" 3665. 统计镜子反射路径数目    中等
给你一个 m x n 的二进制网格 grid，其中：
grid[i][j] == 0 表示一个空格子。grid[i][j] == 1 表示一面镜子。
一个机器人从网格的左上角 (0, 0) 出发，想要到达右下角 (m - 1, n - 1)。它只能向 右 或向 下 移动。
如果机器人试图移入一个有镜子的格子，它会在进入该格子前被 反射：
如果它试图向 右 移动进入镜子，它会被转向 下 方，并移动到镜子正下方的格子里。
如果它试图向 下 移动进入镜子，它会被转向 右 方，并移动到镜子正右方的格子里。
如果这次反射会导致机器人移动到网格边界之外，则该路径被视为无效，不应被计数。
返回从 (0, 0) 到 (m - 1, n - 1) 不同的有效路径数量。由于答案可能非常大，请将其返回对 109 + 7 取模 的结果。
注意：如果一次反射将机器人移动到一个有镜子的格子，机器人会立即再次被反射。
这次反射的方向取决于它进入该镜子的方向：如果它是向右移动进入的，它将被转向下方；如果它是向下移动进入的，它将被转向右方。

示例 1:输入： grid = [[0,1,0],[0,0,1],[1,0,0]];      输出： 5
解释：编号	完整路径
1	(0, 0) → (0, 1) [M] → (1, 1) → (1, 2) [M] → (2, 2)
2	(0, 0) → (0, 1) [M] → (1, 1) → (2, 1) → (2, 2)
3	(0, 0) → (1, 0) → (1, 1) → (1, 2) [M] → (2, 2)
4	(0, 0) → (1, 0) → (1, 1) → (2, 1) → (2, 2)
5	(0, 0) → (1, 0) → (2, 0) [M] → (2, 1) → (2, 2)
[M] 表示机器人试图进入一个有镜子的格子但被反射了。
示例 2:输入： grid = [[0,0],[0,0]];          输出： 2
解释：编号	完整路径
1	(0, 0) → (0, 1) → (1, 1)
2	(0, 0) → (1, 0) → (1, 1)
示例 3:输入： grid = [[0,1,1],[1,1,0]];      输出： 1
解释：编号	完整路径
1	(0, 0) → (0, 1) [M] → (1, 1) [M] → (1, 2)
(0, 0) → (1, 0) [M] → (1, 1) [M] → (2, 1) 超出边界，因此是无效路径。

提示:
m == grid.length
n == grid[i].length
2 <= m, n <= 500
grid[i][j] 的值为 0 或 1。
grid[0][0] == grid[m - 1][n - 1] == 0

"""
from typing import List
from functools import cache

MOD = 1_000_000_007

def uniquePaths(self, grid: List[List[int]]) -> int:
    # @cache
    # def dfs(i, j, k):
    #     if i < 0 or j < 0:
    #         return 0
    #     if i == 0 and j == 0:
    #         return 1
    #     if grid[i][j] == 0:
    #         return (dfs(i, j - 1, 0) + dfs(i - 1, j, 1)) % 1_000_000_007
    #     if k == 0:
    #         return dfs(i - 1, j, 1)
    #     return dfs(i, j - 1, 0)
    #
    # m, n = len(grid), len(grid[0])
    # return dfs(m - 1, n - 1, 0)

    m, n = len(grid), len(grid[0])
    # dp[i][j][0]：竖直向下穿过格子 (i,j) 的路径数
    # dp[i][j][1]：水平向右穿过格子 (i,j) 的路径数
    dp = [[[0, 0] for _ in range(n)] for _ in range(m)]
    dp[0][0] = [1, 1]  # 起点两条通道各算一种走法
    for i in range(m):
        for j in range(n):
            if i == 0 and j == 0:
                continue
            from_up = dp[i - 1][j][0] if i > 0 else 0  # 垂直进入
            from_left = dp[i][j - 1][1] if j > 0 else 0  # 水平进入
            if grid[i][j] == 1:
                # 镜子是方向交换机：垂直进水平出、水平进垂直出
                dp[i][j][0] = from_left % MOD
                dp[i][j][1] = from_up % MOD
            else:
                # 空格是自由广场：进来后想走哪边走哪边，两状态合流
                v = (from_up + from_left) % MOD
                dp[i][j] = [v, v]
    return dp[m - 1][n - 1][0]


